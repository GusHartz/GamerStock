  // ── Batch constants ───────────────────────────────────────────────────────
  // PostgreSQL supports up to 65535 params per query, but large single-query
  // executions have proven unreliable in production (silent failures, timeouts).
  // Strategy: process CS2_VALUES in chunks of BATCH_SIZE entries = 2×BATCH_SIZE params.
  // Each chunk is executed in its own transaction so partial progress is preserved
  // (the idempotency guard detects partial completion on subsequent re-runs).
  const MIGRATION_BATCH_SIZE = 50; // 50 uid+pv pairs = 100 params per query

  export async function runBulkCs2PriceProjectionV2(): Promise<void> {
    const client = await pool.connect();
    try {
      // ── Idempotency check ─────────────────────────────────────────────────────
      const checkResult = await client.query(`
        SELECT COUNT(*)::int AS corrected
        FROM assets
        WHERE asset_uid LIKE 'cs2:cs2:%'
          AND fundamental_price::numeric NOT BETWEEN 14.80 AND 15.20
      `);
      const corrected = Number(checkResult.rows[0]?.corrected ?? 0);

      if (corrected >= 700) {
        console.log(`[Cs2MigV2] Already applied — ${corrected}/800 corrected. Skipping.`);
        return;
      }
      console.log(`[Cs2MigV2] Starting — ${corrected}/800 already corrected, applying fix...`);

      // ── Split into manageable batches ─────────────────────────────────────────
      const entries = Object.entries(CS2_VALUES);
      const total   = entries.length;
      let totalDvs  = 0;
      let totalAf   = 0;
      let totalLtp  = 0;
      let totalAms  = 0;
      let totalHist = 0;

      for (let batchStart = 0; batchStart < total; batchStart += MIGRATION_BATCH_SIZE) {
        const chunk = entries.slice(batchStart, batchStart + MIGRATION_BATCH_SIZE);

        // Build parameterised VALUES rows: ($1::text, $2::numeric), ($3, $4), ...
        const params: (string | number)[] = [];
        const placeholders = chunk.map(([uid, pv]) => {
          params.push(uid, pv);
          const i = params.length;
          return `($${i - 1}::text, $${i}::numeric)`;
        }).join(', ');

        const batchEnd = Math.min(batchStart + MIGRATION_BATCH_SIZE, total);
        console.log(`[Cs2MigV2] Batch ${batchStart + 1}–${batchEnd} / ${total} (${params.length} params)`);

        await client.query("BEGIN");
        try {
          // ── 1. Update dota2_valuation_state.player_value ───────────────────────
          const dvs = await client.query(`
            UPDATE dota2_valuation_state dvs
            SET player_value = v.pv, raw_value = v.pv, updated_at = NOW()
            FROM (VALUES ${placeholders}) AS v(uid, pv)
            JOIN assets a ON a.asset_uid = v.uid
            WHERE dvs.asset_id = a.id
              AND dvs.player_profile_id = 0
              AND dvs.game = 'cs2'
          `, params);
          totalDvs += dvs.rowCount ?? 0;

          // ── 2. Update assets.fundamental_price ──────────────────────────────────
          const af = await client.query(`
            UPDATE assets a
            SET fundamental_price = ROUND(v.pv, 6),
                fundamental_updated_at = NOW(),
                updated_at = NOW()
            FROM (VALUES ${placeholders}) AS v(uid, pv)
            WHERE a.asset_uid = v.uid
              AND a.asset_uid LIKE 'cs2:cs2:%'
          `, params);
          totalAf += af.rowCount ?? 0;

          // ── 3. last_trade_price + price_24h_ago — zero-volume assets only ───────
          const ltp = await client.query(`
            UPDATE assets a
            SET last_trade_price = ROUND(v.pv, 2),
                price_24h_ago    = ROUND(v.pv, 2),
                updated_at       = NOW()
            FROM (VALUES ${placeholders}) AS v(uid, pv)
            WHERE a.asset_uid = v.uid
              AND a.asset_uid LIKE 'cs2:cs2:%'
              AND a.volume_24h = '0.00'
              AND a.last_trade_price BETWEEN 14.80 AND 15.20
          `, params);
          totalLtp += ltp.rowCount ?? 0;

          // ── 4. asset_market_state.last_price — zero-volume assets only ───────────
          const ams = await client.query(`
            UPDATE asset_market_state ams
            SET last_price = ROUND(v.pv, 6), last_updated_at = NOW()
            FROM (VALUES ${placeholders}) AS v(uid, pv)
            JOIN assets a ON a.asset_uid = v.uid
            WHERE ams.asset_id = a.id
              AND a.asset_uid LIKE 'cs2:cs2:%'
              AND a.volume_24h = '0.00'
              AND ams.last_price BETWEEN 14.80 AND 15.20
          `, params);
          totalAms += ams.rowCount ?? 0;

          // ── 5. RECALC history events (idempotent — skip if already present) ──────
          // Only inserts for assets where price differs from baseline AND no RECALC
          // history event exists yet (prevents duplicate history rows on re-run).
          const hist = await client.query(`
            INSERT INTO dota2_value_history (
              asset_id, player_profile_id,
              raw_value_before, raw_value_after, player_value_after,
              confidence_score, event_type, metadata_json
            )
            SELECT
              a.id, 0,
              '15.0000', ROUND(v.pv, 4)::text, ROUND(v.pv, 4)::text,
              '0.5000', 'RECALC',
              '{"source":"cs2_mig_v2","note":"Static dataset from pre-401 PandaScore stats"}'
            FROM (VALUES ${placeholders}) AS v(uid, pv)
            JOIN assets a ON a.asset_uid = v.uid
            WHERE a.asset_uid LIKE 'cs2:cs2:%'
              AND ABS(v.pv - 15.0) > 0.10
              AND NOT EXISTS (
                SELECT 1 FROM dota2_value_history h
                WHERE h.asset_id = a.id
                  AND h.event_type IN ('RECALC', 'BOOTSTRAP')
              )
          `, params);
          totalHist += hist.rowCount ?? 0;

          await client.query("COMMIT");
        } catch (batchErr: any) {
          await client.query("ROLLBACK");
          console.error(
            `[Cs2MigV2] Batch ${batchStart + 1}–${batchEnd} FAILED (rolled back): ` +
            `${batchErr?.message || batchErr}`,
          );
          // Re-throw — outer catch will log and propagate
          throw batchErr;
        }
      }

      console.log(
        `[Cs2MigV2] ✓ Complete — ${total} assets projected. ` +
        `dvs=${totalDvs} fp=${totalAf} ltp=${totalLtp} ams=${totalAms} hist=${totalHist}`,
      );
    } catch (err: any) {
      console.error("[Cs2MigV2] FAILED:", err?.message || err);
      throw err;
    } finally {
      client.release();
    }
  }
